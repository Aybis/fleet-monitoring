function buildSlots(occupied: Record<string, CargoSlotItem>): CargoSlot[] {
  const rows: Array<"A" | "B" | "C"> = ["A", "B", "C"];
  const cols: Array<1 | 2 | 3 | 4 | 5 | 6> = [1, 2, 3, 4, 5, 6];
  const result: CargoSlot[] = [];
  for (const row of rows) {
    for (const col of cols) {
      const id = `${row}${col}`;
      result.push({
        id,
        row,
        col,
        cargo: occupied[id] ?? null,
      });
    }
  }
  return result;
}

function makeGps(lat: number, lng: number, headingDeg: number, lastPing: string, ignitionOn = true) {
  const { x, y } = projectIndonesia(lat, lng);
  return { lat, lng, mapX: x, mapY: y, headingDeg, lastPing, ignitionOn };
}

